// Prepares the photos in public/images/photos for fast delivery. For each photo:
//   1. caps it at 2400px on its long edge and re-encodes it as a progressive
//      mozjpeg (kept only when smaller). This JPEG is the fallback and social image.
//   2. writes AVIF copies at several widths to public/images/opt/, which the
//      site serves directly as static files: no on-demand resizing, no cold
//      starts, cached by browsers and the CDN for a year.
//   3. records the widths and a tiny blurred preview in
//      src/content/image-meta.ts; the preview shows instantly while the photo loads.
//
// Run after adding or replacing a photo:  npm run images
// Give a replaced photo a new file name so cached copies are never reused.
// Uses the sharp package that ships with Next.js.
import { mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "public/images/photos");
const outDir = path.join(root, "public/images/opt");
const MAX_EDGE = 2400;
const WIDTHS = [480, 800, 1200, 1600, 2000, 2400];
const AVIF_QUALITY = 50;

await mkdir(outDir, { recursive: true });
const files = (await readdir(srcDir)).filter((f) => f.endsWith(".jpg")).sort();
const meta = {};
const wanted = new Set();

const fresh = async (file, than) => {
  try {
    return (await stat(file)).mtimeMs >= (await stat(than)).mtimeMs;
  } catch {
    return false;
  }
};

for (const file of files) {
  const key = file.replace(/\.jpg$/, "");
  const full = path.join(srcDir, file);
  let input = await readFile(full);

  const jpeg = await sharp(input)
    .rotate()
    .resize({ width: MAX_EDGE, height: MAX_EDGE, fit: "inside", withoutEnlargement: true })
    .jpeg({ quality: 80, mozjpeg: true, progressive: true })
    .toBuffer();
  if (jpeg.length < input.length * 0.95) {
    await writeFile(full, jpeg);
    input = jpeg;
  }

  const { width } = await sharp(input).metadata();
  const widths = [...new Set([...WIDTHS.filter((w) => w < width), Math.min(width, MAX_EDGE)])];
  for (const w of widths) {
    const out = path.join(outDir, `${key}-${w}.avif`);
    wanted.add(path.basename(out));
    if (await fresh(out, full)) continue;
    await sharp(input).resize({ width: w }).avif({ quality: AVIF_QUALITY }).toFile(out);
  }

  const tiny = await sharp(input).resize(16, 16, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  meta[key] = { widths, blur: `data:image/webp;base64,${tiny.toString("base64")}` };
  console.log(`${file.padEnd(20)} ${width}px  ${(input.length / 1024).toFixed(0)}KB  avif: ${widths.join(", ")}`);
}

// Remove variants of photos that no longer exist.
for (const f of await readdir(outDir)) if (!wanted.has(f)) await rm(path.join(outDir, f));

const body = Object.entries(meta)
  .map(([k, v]) => `  ${JSON.stringify(k)}: { widths: ${JSON.stringify(v.widths)}, blur: ${JSON.stringify(v.blur)} },`)
  .join("\n");
await writeFile(
  path.join(root, "src/content/image-meta.ts"),
  `// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n// AVIF widths available in public/images/opt, and a tiny blurred preview of each photo.\nexport const imageMeta: Record<string, { widths: number[]; blur: string }> = {\n${body}\n};\n`,
);
console.log(`\n${files.length} photos, ${wanted.size} AVIF files`);
